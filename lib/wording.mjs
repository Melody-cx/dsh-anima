/**
 * 把「可能是档位键」的值翻译成文案。
 *
 * @param {string} key 人设字段名（style / headingLists / …）
 * @param {unknown} value 配置里的原值
 * @returns {string|null} 命中档位键时返回文案（**可能是空串**，如 default）；
 *   不是本字段的档位键、或本字段没有档位表时返回 null —— 调用方据此判断
 *   「这是旧版存的键」还是「这是用户自己写的句子」。
 *   注意不能用 `if (result)` 判命中：空串是合法翻译结果。
 */
export function translateWording(key, value) {
  const table = WORDING_TABLES[key]
  if (!table || typeof value !== 'string') return null
  return Object.prototype.hasOwnProperty.call(table, value) ? table[value] : null
}
