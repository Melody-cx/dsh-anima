// lib/wording.mjs — 档位文案表 + 示例表（纯数据，零依赖）
//
// 定位（用户 m06593 拍板「全字段自由文本 + 原档位文案降级为一键填入」）：
//   人设字段**全部改成自由文本**，原来的档位（专业严谨 / 幽默风趣 / 表格增强 …）
//   不再是「只能选这几个」的枚举，而是一段**可以一键填入、随后随便改**的文案模板。
//   于是文案表从「查表渲染」的 lib/prompt.mjs 搬到这里，由另外两个消费者共用：
//     - lib/config.mjs 的迁移路径：旧配置里存的是档位键（'professional'），
//       自动翻译成文案。用户升级后注入提示词的内容一字不变 —— 这是刻意的，
//       否则「升级插件」会等于「偷偷把用户的风格改回默认」。
//     - host 下发给设置页：每个「一键填入」按钮该填什么。
//
//   为什么表不留在这两个消费者各自那边：同一份文案在三处各写一遍，改一处漏两处，
//   而漏掉的那处正是提示词里实际生效的那份。
//
// 文件里的两张表，区别只在「有没有标准答案」：
//   - WORDING_TABLES：风格字段。改回枚举是说得通的，所以每个档位就是一句定稿的话。
//   - FIELD_EXAMPLES：身份与背景字段。**没有**标准答案（谁也不能替用户写他是谁），
//     所以这里给的是**示例**——一段可以直接改成自己情况的现成文字（用户 m08898
//     要求「每个文本都要有例子或者是一些预设」）。示例的作用是消除「空输入框恐惧」：
//     面对一个空 textarea，多数人第一反应是跳过，于是这个字段永远空着。
//
// 一个已知取舍（不是遗漏）：注入进提示词的文案是中文的（含 en 档的 'Reply in English.'），
// 英文界面的用户点「一键填入」会得到中文文案。这与改造前完全一致 —— 语言档一向是
// 「用哪种语言回复」，而不是「插件界面文案用哪种语言」；两者混在一起反而会让
// 中文用户选 en 之后收到英文的解释段。

